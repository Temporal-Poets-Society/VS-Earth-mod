using System;
using System.Linq;
using Vintagestory.API.Common;
using Vintagestory.API.MathTools;
using Vintagestory.API.Server;
using Vintagestory.ServerMods;
using Vintagestory.ServerMods.NoObf;

namespace EarthMap
{
    /// <summary>
    /// The rock floor (Earth tab, EarthParams.RockFloorDepth): the terrain pass lays mantle up to a depth below each chunk's
    /// lowest rock top (TerrainChunkWriter, recorded in the map chunk), this vegetation pass handler makes it plain rock after
    /// caves and ores, and prospecting leaves it out of vanilla's deposit readings (the prospecting adapter, a patch bound by
    /// PatchVanilla).
    /// </summary>
    sealed class RockFloorPass
    {
        /// <summary>Map chunk moddata: the rock floor's top (the terrain pass's mantle), for FillRockFloor and prospecting. The
        /// same text as the world-config key (EarthWorldOptions.RockFloorKey), but another store; saved chunks carry it.</summary>
        internal const string Moddata = "earthRockFloor";
        [ThreadStatic] static int[] floorRocks;

        readonly WorldGenBlocks blocks;
        readonly GlobalConfig gcfg;

        public RockFloorPass(WorldGenBlocks blocks, GlobalConfig gcfg)
        {
            this.blocks = blocks;
            this.gcfg = gcfg;
        }

        /// <summary>
        /// The rock floor's top under a column (0: none), for prospecting: no deposit was placed at or below it (the terrain
        /// pass laid mantle there). Chunks generated by Earth 1.0.3-tall.2, which dropped the record once filled, use the
        /// chunk's lowest terrain height, which puts the floor too high where ice covers the rock.
        /// </summary>
        /// <param name="mapChunk">The map chunk being generated, when the caller has it (W-L4, code review 14 November 2026: a
        /// peeked chunk's own, not the world's at those coordinates); null: the world's.</param>
        internal static int Top(int x, int z, IMapChunk mapChunk = null)
        {
            var w = WorldGenerationContext.Current;
            int depth = w?.Params?.RockFloorDepth ?? 0;
            if (depth <= 0) return 0;
            var map = mapChunk ?? w.Api.WorldManager.GetMapChunk(x / 32, z / 32);
            if (map == null) return 0;
            byte[] stored = map.GetModdata(Moddata);
            if (stored?.Length == 4) return Math.Max(0, BitConverter.ToInt32(stored, 0));
            var heights = map.WorldGenTerrainHeightMap;
            if (heights == null) return 0;
            int min = int.MaxValue;
            foreach (ushort h in heights) min = Math.Min(min, h);
            return Math.Max(0, min - depth);
        }

        /// <summary>
        /// The prospecting adapter. Vanilla's disc deposits (also other mods' and those Earth's ore layer leaves to vanilla) read
        /// the share of host rock in the pick's simulated rock column, which knows no rock floor. They get the column with the
        /// floor's part emptied, so readings, the pick's ore map and prospecting mods that ask the deposits leave out ore that
        /// isn't there. Earth's ore layer reads the floor itself (OreProspecting.EarthColumn).
        /// </summary>
        internal static void RockFloorReading(DiscDepositGenerator __instance, BlockPos pos, ref int[] blockColumn)
        {
            if (pos == null || blockColumn == null) return;
            int top = Top(pos.X, pos.Z);
            // decision 0099: with vanilla rocks, the layers as the world pass laid them under the local ground
            if (EarthVanillaStrata.PickColumn(pos, blockColumn.Length) is int[] laid) blockColumn = laid;
            // 0060: in ore-layer worlds the column is Earth's own blocks in the layers this deposit may use
            EarthWorldGen.Instance?.Api?.ModLoader.GetModSystem<EarthGeology>()?.Layers?.Reading(__instance, pos, top, ref blockColumn);
            if (top <= 0) return;
            var column = (int[])blockColumn.Clone();
            Array.Clear(column, 0, Math.Min(top + 1, column.Length));
            blockColumn = column;
        }

        /// <summary>
        /// The rock floor (EarthParams.RockFloorDepth). The terrain pass left mantle up to it, and caves carved into that and
        /// left air, basalt and lava. After caves and ores it becomes plain rock: in each column the rock just above the floor
        /// (the deepest stratum), with mantle only in the bottom layer. Chunks wholly below the floor are rebuilt from empty, so
        /// their palette holds only those rocks (a bulk fill keeps the old entries). A structure reaching below the floor in
        /// this chunk column (a story location) lowers the floor there to below the structure.
        /// </summary>
        public void Fill(IChunkColumnGenerateRequest request)
        {
            var plainRock = blocks.PlainRock;
            var chunks = request.Chunks;
            var mapChunk = chunks[0].MapChunk;
            byte[] stored = mapChunk.GetModdata(Moddata);
            if (stored == null || stored.Length != 4) return;
            int mantleTop = BitConverter.ToInt32(stored, 0), floor = mantleTop;
            if (mantleTop <= 0) return;
            int x0 = request.ChunkX * 32, z0 = request.ChunkZ * 32;
            var structures = mapChunk.MapRegion?.GeneratedStructures;
            if (structures != null)
            {
                // (W-P4) by index, no copy per chunk: other chunks of the region may add structures meanwhile (the list only
                // grows), and the floor is the lowest of those seen either way
                for (int si = 0; si < structures.Count; si++)
                {
                    GeneratedStructure s;
                    try { s = structures[si]; } catch (ArgumentOutOfRangeException) { break; }
                    var loc = s?.Location;
                    if (loc == null || loc.X2 < x0 || loc.X1 >= x0 + 32 || loc.Z2 < z0 || loc.Z1 >= z0 + 32) continue;
                    floor = Math.Min(floor, loc.Y1 - 1);
                }
            }
            int[] rock = floorRocks ??= new int[32 * 32];
            int found = 0;
            for (int i = 0; i < 32 * 32; i++)
            {
                int id = 0;
                for (int y = mantleTop + 1; y <= mantleTop + 32 && y / 32 < chunks.Length && id == 0; y++)
                {
                    int b = chunks[y / 32].Data.GetBlockIdUnsafe((y % 32) * 32 * 32 + i);
                    if (b > 0 && b < plainRock.Length && plainRock[b]) id = b;
                }
                rock[i] = id;
                if (found == 0) found = id;
            }
            if (found == 0) found = gcfg.defaultRockId;
            bool uniform = true;
            for (int i = 0; i < 32 * 32; i++)
            {
                if (rock[i] == 0) rock[i] = found;
                uniform &= rock[i] == rock[0];
            }

            // between a structure and the terrain pass's mantle top: the mantle left around the structure becomes rock
            int mantle = gcfg.mantleBlockId;
            for (int y = Math.Max(floor + 1, 1); y <= mantleTop; y++)
            {
                var data = chunks[y / 32].Data;
                int i0 = (y % 32) * 32 * 32;
                for (int i = 0; i < 32 * 32; i++) if (data.GetBlockIdUnsafe(i0 + i) == mantle) data.SetBlockUnsafe(i0 + i, rock[i]);
            }
            if (floor < 1) return;

            for (int cy = 0; cy * 32 <= floor; cy++)
            {
                var data = chunks[cy].Data;
                int top = Math.Min(31, floor - cy * 32);
                if (top == 31) data.ClearBlocks();
                for (int ly = 0; ly <= top; ly++)
                {
                    int i0 = ly * 32 * 32;
                    if (cy == 0 && ly == 0) data.SetBlockBulk(0, 32, 32, mantle);
                    else if (uniform) data.SetBlockBulk(i0, 32, 32, rock[0]);
                    else for (int i = 0; i < 32 * 32; i++) data.SetBlockUnsafe(i0 + i, rock[i]);
                    if (top == 31) continue;
                    for (int i = i0; i < i0 + 32 * 32; i++) if (data.GetFluid(i) != 0) data.SetFluid(i, 0);
                }
            }
        }
    }
}
